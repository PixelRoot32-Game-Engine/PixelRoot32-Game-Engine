# 17 groups x 4 frames. Frames grow thin (0) -> thick (3).
# Colors: outer red (RD=9), middle coral (CR=13), core white (WH=15).

def fire_bar_h(t):
    """Horizontal bar, thickness t (rows centered on 7..8)."""
    rows = ['.' * 16 for _ in range(16)]
    r_min = 7 - (t - 1)
    r_max = 8 + (t - 1)
    for r in range(r_min, r_max + 1):
        idx = r - r_min
        color = RD
        if idx >= 2 and idx <= 2 * t - 3:
            color = CR
        if idx >= 3 and idx <= 2 * t - 4:
            color = WH
        rows[r] = hex_c(color) * 16
    return rows


def fire_bar_v(t):
    rows = ['.' * 16 for _ in range(16)]
    c_min = 7 - (t - 1)
    c_max = 8 + (t - 1)
    for r in range(16):
        line = []
        for c in range(16):
            if c_min <= c <= c_max:
                idx = c - c_min
                color = RD
                if idx >= 2 and idx <= 2 * t - 3:
                    color = CR
                if idx >= 3 and idx <= 2 * t - 4:
                    color = WH
                line.append(hex_c(color))
            else:
                line.append('.')
        rows[r] = ''.join(line)
    return rows


def fire_center(t):
    h = fire_bar_h(t)
    v = fire_bar_v(t)
    rows = []
    for r in range(16):
        merged = ''.join(hex_c(WH) if h[r][c] != '.' and v[r][c] != '.' else
                         (h[r][c] if h[r][c] != '.' else v[r][c])
                         for c in range(16))
        rows.append(merged)
    return rows


def fire_tip_h(t, right=True):
    """Horizontal bar with a rounded cap on one end."""
    rows = ['.' * 16 for _ in range(16)]
    r_min = 7 - (t - 1)
    r_max = 8 + (t - 1)
    cap_extra = 1
    cap_range = range(0, 6) if not right else range(10, 16)
    for r in range(r_min, r_max + 1):
        idx = r - r_min
        color = RD
        if idx >= 2 and idx <= 2 * t - 3:
            color = CR
        if idx >= 3 and idx <= 2 * t - 4:
            color = WH
        line = []
        for c in range(16):
            if right:
                if c < 16 - cap_extra and c >= cap_range[0]:
                    line.append(hex_c(color))
                elif c >= 16 - cap_extra:
                    # rounded bulge
                    d = abs(r - 7)
                    if d <= t + 0:
                        line.append(hex_c(RD))
                    else:
                        line.append('.')
                else:
                    line.append('.')
            else:
                if c <= cap_range[-1]:
                    d = abs(r - 7)
                    if d <= t:
                        line.append(hex_c(RD))
                    else:
                        line.append('.')
                elif c < cap_range[-1] + cap_extra + 1:
                    line.append('.')
                else:
                    line.append(hex_c(color))
        rows[r] = ''.join(line)
    return rows


def fire_tip_v(t, down=True):
    v = fire_bar_v(t)
    rows = []
    for r in range(16):
        line = []
        for c in range(16):
            if v[r][c] != '.':
                line.append(v[r][c])
            elif down:
                if r >= 14 - t + 2 and abs(c - 7) <= t:
                    line.append(hex_c(RD))
                else:
                    line.append('.')
            else:
                if r <= t + 1 and abs(c - 7) <= t:
                    line.append(hex_c(RD))
                else:
                    line.append('.')
        rows.append(''.join(line))
    return rows


def hex_c(i):
    return "0123456789ABCDEF"[i]


def gen_explosion_group(kind, t):
    if kind == "CENTER":
        return fire_center(t)
    if kind in ("ARMBASE_HR", "ARNEXT_HR"):
        return fire_bar_h(t)
    if kind in ("ARMBASE_HL", "ARNEXT_HL"):
        return fire_bar_h(t)
    if kind in ("ARMBASE_VD", "ARNEXT_VD"):
        return fire_bar_v(t)
    if kind in ("ARMBASE_VU", "ARNEXT_VU"):
        return fire_bar_v(t)
    if kind == "TIPR":
        return fire_tip_h(t, right=True)
    if kind == "TIPL":
        return fire_tip_h(t, right=False)
    if kind == "TIPD":
        return fire_tip_v(t, down=True)
    if kind == "TIPU":
        return fire_tip_v(t, down=False)
    if kind.startswith("TIP") and kind.endswith("_BASE"):
        base = kind[:-5]
        return gen_explosion_group(base, t)
    raise ValueError(kind)


