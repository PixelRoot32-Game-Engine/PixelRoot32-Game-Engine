def write_player():
    lines = [HEADER_HEAD,
             "// Original CC0 player robot: white body, light-blue visor, coral hands.",
             "// 3 walk frames per direction (Down/Up/Right; Left mirrors Right via",
             "// flipX at draw time) plus 6 death frames.",
             ""]
    groups = [
        ("PLAYER_WALK_DOWN", PLAYER_WALK_DOWN, "kPlayerWalkDown", 3),
        ("PLAYER_WALK_UP", PLAYER_WALK_UP, "kPlayerWalkUp", 3),
        ("PLAYER_WALK_RIGHT", PLAYER_WALK_RIGHT, "kPlayerWalkRight", 3),
        ("PLAYER_DEATH", PLAYER_DEATH, "kPlayerDeath", 6),
    ]
    arrays = {}
    for prefix, data, sym, n in groups:
        for i in range(n):
            name = f"{prefix}_{i}_4BPP"
            arrays[name] = pack(data[i])
            lines += fmt_array(name, arrays[name], f"{prefix} frame {i}")
            lines.append("")
    for prefix, data, sym, n in groups:
        entries = [f"{prefix}_{i}_4BPP" for i in range(n)]
        lines += fmt_sprite4_arr(sym, entries, sym)
        lines.append("")
    lines.append(HEADER_TAIL)
    write("PlayerSprites.h", lines)


def write(name, lines):
    path = os.path.join(ASSETS, name)
    os.makedirs(ASSETS, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {path}")


