def write_tiles():
    lines = [HEADER_HEAD,
             "// Original CC0 board tiles: hard wall (brick), soft wall (crate),",
             "// exit door, and 14 power-up icons.",
             ""]
    tiles = [
        ("HARD_WALL_4BPP", HARD_WALL),
        ("SOFT_WALL_4BPP", SOFT_WALL),
        ("EXIT_4BPP", EXIT),
        ("POWERUP_FIRE_4BPP", POWERUP_FIRE),
        ("POWERUP_BOMB_4BPP", POWERUP_BOMB),
    ]
    for name, art in tiles:
        lines += fmt_array(name, pack(art))
        lines.append("")
    lines += fmt_sprite4("kHardWallSprite", "HARD_WALL_4BPP", PALETTE_MAP, "hard wall tile")
    lines += fmt_sprite4("kSoftWallSprite", "SOFT_WALL_4BPP", PALETTE_MAP, "shared soft-wall tile (all 3 variants)")
    lines += fmt_sprite4("kExitSprite", "EXIT_4BPP", PALETTE_MAP, "exit door")
    lines += fmt_sprite4("kPowerUpFireSprite", "POWERUP_FIRE_4BPP", PALETTE_MAP, "fire power-up")
    lines += fmt_sprite4("kPowerUpBombSprite", "POWERUP_BOMB_4BPP", PALETTE_MAP, "bomb power-up")
    lines.append("")
    # Full power-up sheet (14 original icons)
    for i in range(14):
        art = POWERUP_ALL.get(i)
        if art is None:
            art = POWERUP_FIRE  # fallback, never happens (all defined)
        lines += fmt_array(f"POWERUP_ALL_{i}_4BPP", pack(art))
        lines.append("")
    entries = [f"POWERUP_ALL_{i}_4BPP" for i in range(14)]
    lines += fmt_sprite4_arr("kPowerUpsAll", entries, "full 14-icon power-up sheet")
    lines.append(HEADER_TAIL)
    write("BoardTiles.h", lines)


def write_explosion():
    lines = [HEADER_HEAD,
             "// Original CC0 fire-cross explosion. 17 groups x 4 frames (thin->thick).",
             "// Colors: red outline (9), coral body (D), white core (F).",
             ""]
    arrays = {}
    for group in EXPLOSION_GROUPS:
        for f in range(4):
            t = f + 1
            name = f"EXPLOSION_{group}_{f}_4BPP"
            arrays[name] = pack(gen_explosion_group(group, t))
            lines += fmt_array(name, arrays[name], f"{group} frame {f} (thickness {t})")
            lines.append("")
    lines += fmt_sprite4_arr("kCENTER", [f"EXPLOSION_CENTER_{f}_4BPP" for f in range(4)], "center")
    for group in ("ARMBASE_HR", "ARNEXT_HR", "ARMBASE_HL", "ARNEXT_HL",
                  "ARMBASE_VD", "ARNEXT_VD", "ARMBASE_VU", "ARNEXT_VU",
                  "TIPU", "TIPU_BASE", "TIPD", "TIPD_BASE",
                  "TIPL", "TIPL_BASE", "TIPR", "TIPR_BASE"):
        lines += fmt_sprite4_arr(f"k{group}", [f"EXPLOSION_{group}_{f}_4BPP" for f in range(4)], group)
        lines.append("")
    lines.append(HEADER_TAIL)
    write("ExplosionSprites.h", lines)


