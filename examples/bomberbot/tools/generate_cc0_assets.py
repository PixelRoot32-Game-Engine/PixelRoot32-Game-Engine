"""Generate original CC0 pixel-art headers for the Bomberbot example.

This script produces ORIGINAL sprite data (robot player, slime enemy,
bomb, fire cross explosion, and tiles) designed from scratch. It does NOT
extract or copy any copyrighted game artwork. Only the shared 16-color
palette and the engine's 4bpp packing format are reused.

Packing (matches Sprite4bpp in include/graphics/Renderer.h):
  - 16x16 @ 4bpp -> 8 bytes/row -> 4 uint16_t/row -> 64 uint16_t total.
  - Byte low nibble = left pixel, high nibble = right pixel.
  - uint16 = p0 | p1<<4 | p2<<8 | p3<<12 (little-endian byte order).
  - Palette index 0 in DATA means transparent (never drawn).
"""

