def pack(rows):
    """rows: list of 16 strings, each 16 chars of palette indexes (hex digit or '.'=0).
    Returns list of 64 uint16 values."""
    assert len(rows) == 16, f"need 16 rows, got {len(rows)}"
    out = []
    for row in rows:
        assert len(row) == 16, f"row width != 16: {row!r}"
        pixels = [G if c == '.' else int(c, 16) for c in row]
        for i in range(0, 16, 4):
            p0, p1, p2, p3 = pixels[i], pixels[i + 1], pixels[i + 2], pixels[i + 3]
            out.append(p0 | (p1 << 4) | (p2 << 8) | (p3 << 12))
    assert len(out) == 64
    return out


def fmt_array(name, values, comment=None):
    lines = []
    if comment:
        lines.append(f"// {comment}")
    lines.append(f"static const uint16_t {name}[64] = {{")
    for r in range(16):
        chunk = values[r * 4:(r + 1) * 4]
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in chunk) + ("," if r < 15 else ""))
    lines.append("};")
    return lines


def fmt_sprite4(name, array_name, palette_map, comment=None):
    lines = []
    if comment:
        lines.append(f"// {comment}")
    lines.append(f"static const Sprite4bpp {name} = {{")
    lines.append(f"    reinterpret_cast<const uint8_t*>({array_name}),")
    lines.append(f"    {palette_map}, 16, 16, kBomberbotPaletteSize")
    lines.append("};")
    return lines


def fmt_sprite4_arr(name, entries, comment=None):
    lines = []
    if comment:
        lines.append(f"// {comment}")
    lines.append(f"static const Sprite4bpp {name}[{len(entries)}] = {{")
    for e in entries:
        lines.append(f"    {{ reinterpret_cast<const uint8_t*>({e}),")
        lines.append(f"      {PALETTE_MAP}, 16, 16, kBomberbotPaletteSize }},")
    lines.append("};")
    return lines


