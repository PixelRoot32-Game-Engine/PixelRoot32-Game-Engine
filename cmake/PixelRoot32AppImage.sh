#
# Stages an AppDir for a PixelRoot32 game and turns it into an AppImage.
#
# Called by `pixelroot32_add_appimage()` (see PixelRoot32Game.cmake), and usable
# by hand for the same input:
#
#   PixelRoot32AppImage.sh <binary> <appdir> <name> <display-name> <version> \
#                          <sdl2-runtime|""> <icon|""> <output.AppImage>
#
# The AppDir is an ordinary directory tree:
#
#   AppDir/AppRun                                  entry point (sets the lib path)
#   AppDir/usr/bin/<name>                          the game
#   AppDir/usr/lib/libSDL2-2.0.so.0                the SDL2 runtime, when shared
#   AppDir/usr/share/applications/<name>.desktop   what a desktop menu reads
#
# `appimagetool` (or $APPIMAGETOOL) does the squashfs step. Without it the
# AppDir is still staged — that is the useful half when looking at a layout on
# a machine that has no tool — but the target fails, because a target called
# `<name>_appimage` that silently produces no AppImage is worse than an error.

set -eu

if [ "$#" -ne 8 ]; then
    echo "usage: $0 <binary> <appdir> <name> <display-name> <version> <sdl2-runtime> <icon> <output>" >&2
    exit 2
fi

binary=$1
appdir=$2
name=$3
display_name=$4
version=$5
sdl2_runtime=$6
icon=$7
output=$8

if [ ! -f "$binary" ]; then
    echo "error: '$binary' is not a file; build the game first" >&2
    exit 1
fi

rm -rf "$appdir"
mkdir -p "$appdir/usr/bin" \
         "$appdir/usr/lib" \
         "$appdir/usr/share/applications"

install -m 0755 "$binary" "$appdir/usr/bin/$name"

# SDL2 is a public dependency: on a distribution SDL2 lives in
# /usr/lib/<triplet>, which target machines cannot be assumed to have. The
# loader asks for the SONAME, so the file has to be there under that name and
# not only under the versioned one it is stored as.
if [ -n "$sdl2_runtime" ]; then
    # The copy is stored under its SONAME, not under the name it happens to
    # have on this machine: the file handed over by CMake is whatever the found
    # package calls it (often the unversioned `libSDL2.so` development symlink),
    # while the loader asks for `libSDL2-2.0.so.0`.
    soname=$(objdump -p "$sdl2_runtime" 2>/dev/null | awk '/SONAME/ {print $2; exit}')
    if [ -z "$soname" ]; then
        soname=libSDL2-2.0.so.0
    fi
    install -m 0644 "$sdl2_runtime" "$appdir/usr/lib/$soname"
fi

# The icon lives at the AppDir root, not under usr/share/icons/hicolor/<size>: the
# root copy (and .DirIcon) is what appimagetool and the AppImage desktop
# integration read, and it makes no claim about the image's size. Ship the size
# you want the menu to use.
if [ -n "$icon" ]; then
    if [ ! -f "$icon" ]; then
        echo "error: icon '$icon' does not exist" >&2
        exit 1
    fi
    install -m 0644 "$icon" "$appdir/$name.png"
    install -m 0644 "$icon" "$appdir/.DirIcon"
fi

cat > "$appdir/AppRun" <<EOF
#!/bin/sh
# Generated by PixelRoot32AppImage.sh. The AppImage is mounted somewhere
# temporary, so everything is resolved relative to this file.
HERE=\$(dirname "\$(readlink -f "\$0")")
export LD_LIBRARY_PATH="\$HERE/usr/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec "\$HERE/usr/bin/$name" "\$@"
EOF
chmod 0755 "$appdir/AppRun"

# The desktop file goes in two places: `appimagetool` reads the one at the
# AppDir root (a desktop file only under usr/share/applications makes it abort
# with "Desktop file not found"), and the copy under usr/share/applications is
# what a desktop menu integrates when the AppImage is installed system-wide.
{
    echo "[Desktop Entry]"
    echo "Type=Application"
    echo "Name=$display_name"
    echo "Exec=$name"
    echo "Terminal=false"
    echo "Categories=Game;"
    echo "Comment=Built with PixelRoot32 Game Engine $version"
    echo "X-AppImage-Version=$version"
    if [ -n "$icon" ]; then
        echo "Icon=$name"
    fi
} > "$appdir/$name.desktop"
install -m 0644 "$appdir/$name.desktop" "$appdir/usr/share/applications/$name.desktop"

tool=${APPIMAGETOOL:-}
if [ -z "$tool" ] || [ ! -x "$tool" ]; then
    cat >&2 <<EOF
error: appimagetool was not found, so no AppImage was produced.
       The AppDir is staged at: $appdir
       Install appimagetool and either put it in PATH or reconfigure with
       -DPIXELROOT32_APPIMAGETOOL=/path/to/appimagetool
EOF
    exit 1
fi

# Modern distributions ship no FUSE 2, and appimagetool is itself an AppImage:
# `--appimage-extract-and-run` runs it without mounting, which is what makes it
# work on a CI runner. ARCH matters because the tool also runs on non-x86 hosts.
ARCH=${ARCH:-$(uname -m)}
export ARCH
"$tool" --appimage-extract-and-run --no-appstream "$appdir" "$output"

echo "AppImage: $output"
