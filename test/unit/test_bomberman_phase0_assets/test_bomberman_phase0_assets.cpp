// =============================================================================
// Slicing correctness — frame data must not be all zeros (regression guard)
// =============================================================================

/**
 * @test At least one entry in each major frame array is non-zero.
 * @expected Guards against a regression where placeholder zeros are committed
 *   instead of real pixel data from the local NES sheet.
 */
void test_frame_data_is_not_all_zeros(void) {
    auto has_nonzero = [](const uint16_t* arr, size_t n) {
        for (size_t i = 0; i < n; i++) if (arr[i] != 0) return true;
        return false;
    };
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(HARD_WALL_4BPP, 64), "HARD_WALL_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(SOFT_WALL_4BPP, 64), "SOFT_WALL_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(EXIT_4BPP, 64), "EXIT_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(POWERUP_FIRE_4BPP, 64), "POWERUP_FIRE_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(POWERUP_BOMB_4BPP, 64), "POWERUP_BOMB_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(BOMB_FRAME_0_4BPP, 64), "BOMB_FRAME_0_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(PLAYER_WALK_DOWN_0_4BPP, 64), "PLAYER_WALK_DOWN_0_4BPP is all zeros");
    TEST_ASSERT_TRUE_MESSAGE(has_nonzero(ENEMY_BALLOM_WALK_0_4BPP, 64), "ENEMY_BALLOM_WALK_0_4BPP is all zeros");
}

