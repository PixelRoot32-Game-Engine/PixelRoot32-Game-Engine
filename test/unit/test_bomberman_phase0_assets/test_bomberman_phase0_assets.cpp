/**
 * @test Palette index 0 is transparent
 * @expected BOMBERMAN_SPRITE_PALETTE_RGB565[0] == 0x0000
 */
void test_palette_index_zero_is_transparent(void) {
    TEST_ASSERT_EQUAL_UINT16(0x0000, BOMBERMAN_SPRITE_PALETTE_RGB565[0]);
}

/**
 * @test Palette mapping size matches kBombermanPaletteSize
 * @expected sizeof(BOMBERMAN_PALETTE_MAPPING) / sizeof(Color) == kBombermanPaletteSize
 */
void test_palette_mapping_size_matches(void) {
    TEST_ASSERT_EQUAL(kBombermanPaletteSize,
                      static_cast<int>(sizeof(BOMBERMAN_PALETTE_MAPPING) / sizeof(Color)));
}

/**
 * @test RGB565 conversion boundary: white and black
 * @expected (255>>3)<<11 | (255>>2)<<5 | (255>>3) == 0xFFFF
 *          (0>>3)<<11 | (0>>2)<<5 | (0>>3) == 0x0000
 */
void test_rgb565_conversion_boundary(void) {
    uint16_t white565 = (uint16_t)((255 >> 3) << 11) | (uint16_t)((255 >> 2) << 5) | (uint16_t)(255 >> 3);
    uint16_t black565 = (uint16_t)((0 >> 3) << 11) | (uint16_t)((0 >> 2) << 5) | (uint16_t)(0 >> 3);
    TEST_ASSERT_EQUAL_UINT16(0xFFFF, white565);
    TEST_ASSERT_EQUAL_UINT16(0x0000, black565);
}

